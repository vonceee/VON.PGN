function createBlankBoard(coreGoal = 'My Ultimate Goal'): MandalartBoard {
  const pillarTitles = [
    'Pillar 1',
    'Pillar 2',
    'Pillar 3',
    'Pillar 4',
    'Pillar 5',
    'Pillar 6',
    'Pillar 7',
    'Pillar 8',
  ];

  return {
    id: 'blank-template',
    version: 1,
    coreGoal,
    subtitle: 'Define your 8 foundational pillars and 64 daily actionable habits',
    category: 'custom',
    updatedAt: new Date().toISOString(),
    pillars: pillarTitles.map((title, pIndex) => ({
      id: `p-${pIndex}`,
      index: pIndex,
      title,
      actions: Array.from({ length: 8 }, (_, aIndex) => ({
        id: `p-${pIndex}-a-${aIndex}`,
        title: `Action ${aIndex + 1}`,
        completed: false,
      })),
    })),
  };
}

